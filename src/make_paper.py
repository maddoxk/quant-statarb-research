A(r"\section{Limitations}")
A(r"Several caveats temper these results. (i) The hedge ratio and cointegrating")
A(r"relationship are estimated \emph{in-sample} over the full window; a live strategy")
A(r"must re-estimate on a rolling basis, and the relationship can break down")
A(r"(cointegration is not guaranteed to persist). (ii) We assume fills at the daily")
A(r"close and a constant proportional cost; real execution incurs slippage, bid--ask")
A(r"spread, and borrow costs on the short leg. (iii) We ignore financing, dividends on")
A(r"the legs, and capacity constraints. (iv) The single-pair sample makes the Sharpe")
A(r"estimate noisy; a production system would diversify across many cointegrated")
A(r"pairs. (v) Multiple-testing / data-snooping bias inflates apparent significance")
A(r"when pairs are selected by searching. These are standard but material concerns in")
A(r"the stat-arb literature~\cite{chan2013,vidyamurthy2004}.")
