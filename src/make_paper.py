A(r"\section{Introduction}")
A(r"Statistical arbitrage exploits temporary mispricings between securities whose")
A(r"prices share a common stochastic trend. When two non-stationary price series are")
A(r"\emph{cointegrated}, a linear combination of them is stationary and")
A(r"mean-reverting~\cite{engle1987,vidyamurthy2004}. A trader can therefore short the")
A(r"spread when it is unusually high and buy it when unusually low, profiting as it")
A(r"reverts to its long-run mean. This paper implements the full pipeline---universe")
A(r"selection, cointegration testing, hedge-ratio estimation, signal construction,")
A(r"and a cost-aware backtest---and reports honest, reproducible performance metrics.")
