A(r"\section{Methodology}")
A(r"\subsection{Cointegration}")
A(r"Let $p^y_t$ and $p^x_t$ be the two price series. They are cointegrated of order")
A(r"$(1,1)$ if each is integrated of order one, $I(1)$, but there exists $\beta$ such")
A(r"that the spread")
A(r"\begin{equation}")
A(r"s_t = p^y_t - \alpha - \beta\, p^x_t")
A(r"\end{equation}")
A(r"is stationary, $s_t \sim I(0)$. The \textbf{Engle--Granger} procedure estimates")
A(r"$(\alpha,\beta)$ by OLS and then applies an Augmented Dickey--Fuller (ADF) test")
A(r"to the residuals $\hat{s}_t$, testing")
A(r"\begin{equation}")
A(r"\Delta \hat{s}_t = \gamma\, \hat{s}_{t-1}")
A(r"   + \sum_{i=1}^{k}\phi_i\,\Delta \hat{s}_{t-i} + \varepsilon_t,")
A(r"\qquad H_0:\ \gamma = 0\ \text{(unit root, no cointegration).}")
A(r"\end{equation}")
A(r"The \textbf{Johansen} test instead estimates a vector error-correction model")
A(r"$\Delta \mathbf{P}_t = \Pi \mathbf{P}_{t-1} + \sum_i \Gamma_i \Delta\mathbf{P}_{t-i}")
A(r"+ \boldsymbol{\varepsilon}_t$ and tests the rank of $\Pi$ via the trace statistic")
A(r"$\lambda_{\text{trace}}(r) = -T\sum_{i=r+1}^{n}\ln(1-\hat\lambda_i)$, where")
A(r"$\hat\lambda_i$ are the ordered eigenvalues.")
A("")
A(r"\subsection{Hedge ratio and spread}")
A(r"The OLS hedge ratio $\hat\beta$ minimises $\sum_t (p^y_t - \alpha - \beta p^x_t)^2$,")
A(r"giving $\hat\beta = \mathrm{Cov}(p^y,p^x)/\mathrm{Var}(p^x)$. The traded spread is")
A(r"$\hat{s}_t = p^y_t - \hat\alpha - \hat\beta\, p^x_t$.")
A("")
A(r"\subsection{Z-score trading signal}")
A(f"We standardise the spread with a rolling window of $w={p['window']}$ days:")
A(r"\begin{equation}")
A(r"z_t = \frac{s_t - \mu_t^{(w)}}{\sigma_t^{(w)}},\qquad")
A(r"\mu_t^{(w)} = \frac{1}{w}\sum_{i=0}^{w-1}s_{t-i},\quad")
A(r"\sigma_t^{(w)} = \sqrt{\frac{1}{w}\sum_{i=0}^{w-1}\!\left(s_{t-i}-\mu_t^{(w)}\right)^2}.")
A(r"\end{equation}")
A(f"With entry threshold $z^\\ast={p['entry']:g}$ and exit threshold")
A(f"$z^{{\\text{{exit}}}}={p['exit']:g}$, the target position on the spread is")
A(r"\begin{equation}")
A(r"\pi_t =")
A(r"\begin{cases}")
A(r"+1 & \text{enter long spread when } z_t \le -z^\ast,\\")
A(r"-1 & \text{enter short spread when } z_t \ge +z^\ast,\\")
A(r"0  & \text{exit when } |z_t| \le z^{\text{exit}},\\")
A(r"\pi_{t-1} & \text{otherwise (hold).}")
A(r"\end{cases}")
A(r"\end{equation}")
A(f"A long-spread position is long one unit of {y} and short $\\hat\\beta$ units of")
A(f"{x}. Figure~\\ref{{fig:spread}} plots the spread and its z-score with the trading")
A(r"bands.")
A("")
A(r"\begin{figure}[H]\centering")
A(r"\includegraphics[width=0.85\textwidth]{figures/spread_zscore.png}")
A(f"\\caption{{Top: the OLS spread $s_t$. Bottom: its rolling z-score with entry")
A(f"($\\pm{p['entry']:g}$, dashed) and exit ($\\pm{p['exit']:g}$, dotted) bands.}}")
A(r"\label{fig:spread}")
A(r"\end{figure}")
A("")
A(r"\subsection{Backtest and performance metrics}")
A(r"The strategy log-return uses the \emph{lagged} position to avoid look-ahead:")
A(r"\begin{equation}")
A(r"r_t = \pi_{t-1}\, w\big(\Delta\ln p^y_t - \hat\beta\,\Delta\ln p^x_t\big) - \kappa_t,")
A(r"\qquad w = \frac{1}{1+|\hat\beta|},")
A(r"\end{equation}")
A(r"where $\kappa_t = c\cdot|\pi_t-\pi_{t-1}|\cdot w(1+|\hat\beta|)$ are proportional")
A(r"transaction costs at $c$ basis points per side. The annualised Sharpe ratio is")
A(r"\begin{equation}")
A(r"\mathrm{SR} = \sqrt{252}\,\frac{\bar r}{\hat\sigma_r},")
A(r"\end{equation}")
A(r"and the maximum drawdown of the equity curve $E_t = \prod_{\tau\le t}(1+r_\tau)$ is")
A(r"$\mathrm{MDD} = \min_t\big(E_t/\max_{\tau\le t}E_\tau - 1\big)$.")
A("")
