def sens_table():
    rows = []
    rows.append(r"\begin{tabular}{l" + "r" * len(s["costs"]) + "}")
    rows.append(r"\toprule")
    rows.append(r"Entry $z^\ast$ & " + " & ".join(f"{cc:g}\\,bps" for cc in s["costs"]) + r" \\")
    rows.append(r"\midrule")
    for e, row in zip(s["entries"], s["sharpe_grid"]):
        rows.append(f"{e:g} & " + " & ".join(f"{v:.2f}" for v in row) + r" \\")
    rows.append(r"\bottomrule")
    rows.append(r"\end{tabular}")
    return "\n".join(rows)


